#!/bin/sh
# Packs a gem and its runtime dependencies into a jar the browser JVM loads from the classpath
# (like JRuby's own stdlib). RubyGems stays off in the page; `require '<entry>'` puts each bundled
# gem's require_paths on $LOAD_PATH and requires the gem.
#
#   patch/gems/build.sh <jar-name> <entry> <gem> <version> [gem-to-skip ...]
#   e.g. patch/gems/build.sh sequel-gems sequel-cheerpj sequel 5.109.0 bigdecimal
#        -> jars/sequel-gems.jar, used as: require 'sequel-cheerpj'
#
# Gems are installed with the stock JRuby jar on the host JVM (needs network + a JDK).
# JRUBY_JAR overrides the JRuby jar.
set -eu
cd "$(dirname "$0")/../.."
[ $# -ge 4 ] || { echo "usage: $0 <jar-name> <entry> <gem> <version> [gem-to-skip ...]" >&2; exit 2; }
NAME=$1 ENTRY=$2 GEM=$3 GEM_VERSION=$4
shift 4
SKIP="$*"
JRUBY_JAR=${JRUBY_JAR:-jars/jruby-complete-9.4.15.0.jar}
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
java -jar "$JRUBY_JAR" -S gem install "$GEM" -v "$GEM_VERSION" -i "$work/home" --no-document --quiet
mkdir -p "$work/jar/$NAME"
# Each gem's require_paths from its gemspec (facets uses lib/core + lib/standard, etc.).
SKIP="$SKIP" GEM_HOME="$work/home" GEM_PATH="$work/home" java -jar "$JRUBY_JAR" -e '
  skip = ENV["SKIP"].split
  Gem::Specification.each do |s|
    next unless s.gem_dir.start_with?(ENV["GEM_HOME"])   # skip the default gems inside the JRuby jar
    next if skip.include?(s.name)
    s.require_paths.each { |r| puts "#{s.full_name}/#{r}" }
  end' > "$work/paths"
dirs=$(cut -d/ -f1 "$work/paths" | sort -u)
for name in $dirs; do
  cp -R "$work/home/gems/$name" "$work/jar/$NAME/"
  rm -rf "$work/jar/$NAME/$name/samples" "$work/jar/$NAME/$name/test" "$work/jar/$NAME/$name/spec"
done
# Java extensions (e.g. concurrent-ruby's): put their classes on the classpath directly, since
# CheerpJ can't load a jar nested inside a jar at runtime.
find "$work/jar/$NAME" -name '*.jar' | while read -r ext; do
  (cd "$work/jar" && unzip -q -o "$ext" -x 'META-INF/*')
done
{
  echo "# Generated by patch/gems/build.sh: bundled $GEM $GEM_VERSION and its dependencies."
  echo "%w["
  sed 's/^/  /' "$work/paths"
  echo "].reverse_each { |p| \$LOAD_PATH.unshift(\"uri:classloader:/$NAME/#{p}\") }"
  echo "require '$GEM'"
} > "$work/jar/$ENTRY.rb"
jar --create --file "jars/$NAME.jar" --date=2026-01-01T00:00:00Z -C "$work/jar" .
echo "built jars/$NAME.jar ($GEM $GEM_VERSION, $(echo $dirs | wc -w) gems; require '$ENTRY')"
